/**
 * เลขเงินเปล่า ไม่มี ฿ นำหน้า — สำหรับข้อความที่ลงท้ายด้วยคำว่า "บาท"
 * (ข้อความทวงหนี้ที่ก๊อปส่งลูกค้า · ตัวอย่างคำนวณเรตต้นทุน · ความพร้อมผลิต)
 * ใช้ formatBaht กับที่นี่ไม่ได้ เพราะจะกลายเป็น "฿1,449.00 บาท"
 */
export function formatAmount(amount: number): string {
  // เศษติดลบที่ปัดแล้วเหลือศูนย์ต้องไม่กลายเป็น "-0.00" — ตัวนี้ไปอยู่ในจดหมายทวงหนี้
  // ที่ก๊อปส่งลูกค้าจริง (formatBaht กันไว้อยู่แล้ว ตัวนี้เคยลืม)
  const digits = Math.abs(amount).toLocaleString("th-TH", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  return amount < 0 && digits !== "0.00" ? `-${digits}` : digits;
}

/**
 * เงินเต็มยอดพร้อม ฿ — ยอดในเอกสาร ตาราง บรรทัดสรุป และบรรทัดที่คนตรวจก่อนกดยืนยัน
 * ติดลบขึ้นเครื่องหมายไว้หน้า ฿ ("-฿1,449.50") ไม่ใช่ "฿-1,449.50"
 * เศษจาก floating-point ที่ติดลบนิดเดียว (-0.004) ต้องไม่กลายเป็น "-฿0.00"
 */
export function formatBaht(amount: number): string {
  const digits = formatAmount(Math.abs(amount));
  const sign = amount < 0 && digits !== "0.00" ? "-" : "";
  return `${sign}฿${digits}`;
}

/**
 * เงินบนช่องตัวเลขใหญ่ — ตัดทศนิยมทิ้งให้อ่านเร็ว (เดิม moneyTile ของหน้าแรก)
 * ใช้เฉพาะการ์ดสรุป ห้ามใช้กับยอดที่คนต้องเอาไปกระทบกับเอกสารหรือช่องกรอก
 */
export function formatBahtRounded(amount: number): string {
  // ปัดเศษด้วย Intl ทางเดียว แล้วค่อยเติมเครื่องหมาย — ยอดติดลบที่ปัดแล้วเหลือ 0 ต้องไม่ขึ้น "-฿0"
  const whole = Math.abs(amount).toLocaleString("th-TH", { maximumFractionDigits: 0 });
  const sign = amount < 0 && whole !== "0" ? "-" : "";
  return `${sign}฿${whole}`;
}
